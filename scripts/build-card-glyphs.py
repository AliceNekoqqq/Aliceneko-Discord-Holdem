"""Build the small font atlas used by the dependency-free Worker PNG renderer.

Run with Pillow and DejaVu Sans installed; runtime needs neither.
"""
import base64
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 48)
glyphs = {}
for char in '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ /-♠♥♦♣':
    box = font.getbbox(char)
    width = max(1, box[2] - box[0])
    height = max(1, box[3] - box[1])
    image = Image.new('L', (width, height))
    ImageDraw.Draw(image).text((-box[0], -box[1]), char, font=font, fill=255)
    glyphs[char] = [width, height, round(font.getlength(char)), base64.b64encode(image.tobytes()).decode()]
target = Path(__file__).resolve().parents[1] / 'card-glyphs.mjs'
target.write_text('// Generated by scripts/build-card-glyphs.py; see FONT_LICENSE.txt.\nexport const glyphs=' + json.dumps(glyphs, separators=(',', ':')) + ';\n')
