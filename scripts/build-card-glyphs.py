"""Build the small font atlas used by the dependency-free Worker PNG renderer.

Run with Pillow and DejaVu Sans installed; runtime needs neither.
"""
import base64
import json
import argparse
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 48)
parser = argparse.ArgumentParser()
parser.add_argument('--cjk-font', required=True, help='Path to original Noto Sans CJK SC font')
args = parser.parse_args()
cjk = ImageFont.truetype(args.cjk_font, 48)
glyphs = {}
fixed = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz ._!?/#+-♠♥♦♣你的底牌仅可见桌面公共所有人用翻转河手绿框出灰等候行动本局结束当前颜色红黄蓝最近点击编号第页剩余张可跳过反变金抢成功玩家座位顺时针逆队主电脑等待加入发中罚累计胜者全桌窗口下一轮到刚了桌固定绿框金框粉条方向箭头关闭无未'
source = (Path(__file__).resolve().parents[1] / 'uno-image.mjs').read_text()
for char in dict.fromkeys(fixed + ''.join(re.findall('[\u4e00-\u9fff]', source))):
    face = cjk if ord(char) > 0x4e00 else font
    box = face.getbbox(char)
    width = max(1, box[2] - box[0])
    height = max(1, box[3] - box[1])
    image = Image.new('L', (width, height))
    ImageDraw.Draw(image).text((-box[0], -box[1]), char, font=face, fill=255)
    glyphs[char] = [width, height, round(face.getlength(char)), base64.b64encode(image.tobytes()).decode()]
target = Path(__file__).resolve().parents[1] / 'card-glyphs.mjs'
target.write_text('// Generated by scripts/build-card-glyphs.py; see FONT_LICENSE.txt.\nexport const glyphs=' + json.dumps(glyphs, separators=(',', ':')) + ';\n')
