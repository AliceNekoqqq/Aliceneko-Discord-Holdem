#!/usr/bin/env python3
"""Pack the 13 illustrated product assets; retain validated JPEGs if originals are absent."""
import base64
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'assets/equipment-art'
IDS = ['coffee-machine', 'baking-oven', 'blender', 'ice-cream-maker', 'americano', 'redbean-latte', 'cappuccino', 'butter-croissant', 'cheese-toast', 'berry-smoothie', 'mango-yogurt', 'vanilla-sundae', 'redbean-parfait']

def main():
    manifest = {}
    for asset_id in IDS:
        jpeg = DIRECTORY / f'{asset_id}.jpg'
        original = DIRECTORY / 'original' / f'{asset_id}.png'
        if original.exists():
            with Image.open(original) as source:
                converted = source.convert('RGB')
                converted.thumbnail((768, 768), Image.Resampling.LANCZOS)
                if converted.size != (768, 768):
                    raise ValueError(f'{asset_id}: square 768px required')
                converted.save(jpeg, 'JPEG', quality=78, optimize=True)
        with Image.open(jpeg) as published:
            if published.size != (768, 768) or published.format != 'JPEG':
                raise ValueError(f'{asset_id}: invalid published JPEG')
        payload = jpeg.read_bytes()
        record = dict(id=asset_id, mime='image/jpeg', bytes=len(payload), width=768, height=768,
                      sha256=hashlib.sha256(payload).hexdigest(), file=str(jpeg.relative_to(ROOT)))
        manifest[asset_id] = record
        (ROOT / f'equipment-art-data-{asset_id}.mjs').write_text('// Generated by scripts/build-equipment-art.py\nexport default ' + json.dumps(dict(mime='image/jpeg', base64=base64.b64encode(payload).decode())) + ';\n')
    (ROOT / 'equipment-art-manifest.mjs').write_text('// Generated by scripts/build-equipment-art.py\nexport default ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n')
    imports = '\n'.join(f"import image{i} from './equipment-art-data-{asset_id}.mjs';" for i, asset_id in enumerate(IDS))
    values = ',\n'.join(f'  {json.dumps(asset_id)}: image{i}' for i, asset_id in enumerate(IDS))
    (ROOT / 'equipment-art-data.mjs').write_text('// Generated by scripts/build-equipment-art.py\n' + imports + '\nexport default {\n' + values + '\n};\n')
    (DIRECTORY / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(dict(images=len(manifest), bytes=sum(x['bytes'] for x in manifest.values()))))

if __name__ == '__main__':
    main()
