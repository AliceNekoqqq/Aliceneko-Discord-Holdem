"""Build compressed binary CJK glyph blocks without Base64 payloads."""
import argparse
import json
import struct
import zlib
from pathlib import Path
from PIL import Image, ImageFont, ImageDraw
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--font", required=True)
args = parser.parse_args()
font = ImageFont.truetype(args.font, 24)
known = TTFont(args.font).getBestCmap()
blocks = {}
ranges = [(0xa0,0x250),(0x370,0x530),(0x3000,0x3100),(0x3400,0xa000),(0xf900,0xfb00)]
for low, high in ranges:
    for code in range(low, high):
        if code not in known:
            continue
        char = chr(code)
        box = font.getbbox(char)
        image = Image.new("1", (24,24))
        ImageDraw.Draw(image).text((-box[0],-box[1]), char, font=font, fill=1)
        pixels = image.tobytes()
        if len(pixels) != 72:
            raise ValueError(f"Unexpected 24x24 packed glyph size: {len(pixels)}")
        block = code // 256
        blocks.setdefault(block, []).append((code, round(font.getlength(char)), pixels))
atlas = bytearray()
manifest = {}
for block, entries in sorted(blocks.items()):
    raw = bytearray()
    for code, advance, pixels in entries:
        raw.extend(struct.pack(">IH", code, advance))
        raw.extend(pixels)
    compressed = zlib.compress(raw, 9)
    manifest[str(block)] = [len(atlas), len(compressed)]
    atlas.extend(compressed)
asset_dir = ROOT / "assets" / "renderer"
asset_dir.mkdir(parents=True, exist_ok=True)
(asset_dir / "nickname-glyphs.bin").write_bytes(atlas)
(ROOT / "nickname-glyphs.mjs").write_text(
    "// Generated by scripts/build-nickname-glyphs.py; Noto CJK, NOTO_FONT_LICENSE.txt.\n"
    + "export const nicknameBlocks=" + json.dumps(manifest, separators=(",", ":")) + ";\n"
    + "export const nicknameAtlas=" + json.dumps({"bytes": len(atlas)}) + ";\n"
)
print(json.dumps({"glyphs": sum(map(len, blocks.values())), "blocks": len(blocks), "binary_bytes": len(atlas)}))
