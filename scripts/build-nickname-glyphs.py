"""Build bounded, compressed 24px nickname glyph blocks from Noto CJK (OFL)."""
import argparse,base64,json,zlib
from pathlib import Path
from PIL import Image,ImageFont,ImageDraw
from fontTools.ttLib import TTFont
parser=argparse.ArgumentParser();parser.add_argument('--font',required=True);args=parser.parse_args()
font=ImageFont.truetype(args.font,24);known=TTFont(args.font).getBestCmap();blocks={}
ranges=[(0xa0,0x250),(0x370,0x530),(0x3000,0x3100),(0x3400,0xa000),(0xf900,0xfb00)]
for lo,hi in ranges:
 for code in range(lo,hi):
  if code not in known:continue
  char=chr(code);box=font.getbbox(char);im=Image.new('1',(24,24));ImageDraw.Draw(im).text((-box[0],-box[1]),char,font=font,fill=1)
  block=code//256;blocks.setdefault(block,[]).append([code,round(font.getlength(char)),base64.b64encode(im.tobytes()).decode()])
result={k:base64.b64encode(zlib.compress(json.dumps(v,separators=(',',':')).encode(),9)).decode() for k,v in blocks.items()}
path=Path(__file__).resolve().parents[1]/'nickname-glyphs.mjs';path.write_text('// Generated by scripts/build-nickname-glyphs.py; Noto CJK, NOTO_FONT_LICENSE.txt.\nexport const nicknameBlocks='+json.dumps(result,separators=(',',':'))+';\n')
print(json.dumps({'glyphs':sum(map(len,blocks.values())),'blocks':len(blocks),'bytes':path.stat().st_size}))
