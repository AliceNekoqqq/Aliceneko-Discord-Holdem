#!/usr/bin/env python3
"""Pack the fifteen imagegen portraits for the bot; reuse repository JPEGs on rebuild."""
import base64
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets' / 'pets'
PAIRS = {
    'lamp-cat': ['amber', 'silver', 'calico'],
    'moss-dog': ['moss', 'cocoa', 'cream'],
    'paper-sparrow': ['rice', 'ink', 'rose'],
    'dusk-rabbit': ['lavender', 'peach', 'moon'],
    'river-otter': ['chestnut', 'slate', 'honey'],
}

records, manifest = {}, []
for species, coats in PAIRS.items():
    for coat in coats:
        stem = f'{species}-{coat}-v1'
        original, packed = ASSETS / f'{stem}.png', ASSETS / f'{stem}.jpg'
        if original.exists():
            with Image.open(original) as image:
                if image.mode == 'RGBA' and image.getchannel('A').getextrema()[0] != 255:
                    raise ValueError(f'Expected opaque card background: {original}')
                image = image.convert('RGB')
                image.thumbnail((768, 768), Image.Resampling.LANCZOS)
                image.save(packed, 'JPEG', quality=88, optimize=True, progressive=True)
        if not packed.exists():
            raise FileNotFoundError(f'Missing generated portrait: {stem}')
        data = packed.read_bytes()
        with Image.open(packed) as image:
            width, height = image.size
            if image.format != 'JPEG' or width != height or width < 512:
                raise ValueError(f'Invalid packed portrait: {packed}')
        sha = hashlib.sha256(data).hexdigest()
        records[f'{species}:{coat}'] = {'base64': base64.b64encode(data).decode(), 'bytes': len(data), 'sha256': sha}
        manifest.append({'species': species, 'coat': coat, 'path': str(packed.relative_to(ROOT)),
                         'width': width, 'height': height, 'bytes': len(data), 'sha256': sha, 'source': 'imagegen'})
(ROOT / 'pet-art-data.mjs').write_text('// Generated by scripts/build-pet-art.py; original artwork made with imagegen.\nexport default ' + json.dumps(records, separators=(',', ':')) + ';\n')
(ASSETS / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
print(json.dumps({'portraits': len(manifest), 'jpeg_bytes': sum(x['bytes'] for x in manifest)}))
