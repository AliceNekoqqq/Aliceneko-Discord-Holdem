#!/usr/bin/env python3
"""Build optimized tavern JPEGs and the Worker-embedded payload module."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {"room": (960, 640), "milk": (512, 512), "cake": (512, 512), "mushroom-noodles": (512, 512)}
LIMIT = 180 * 1024


def build(pairs):
    supplied = dict(pairs)
    if set(supplied) != set(TARGETS):
        raise SystemExit("provide exactly room, milk, cake, mushroom-noodles as ID=PATH pairs")
    out = ROOT / "assets" / "art"
    out.mkdir(parents=True, exist_ok=True)
    manifest = {}
    encoded = {}
    for asset_id, size in TARGETS.items():
        with Image.open(supplied[asset_id]) as source:
            image = source.convert("RGB")
            image.thumbnail(size, Image.Resampling.LANCZOS)
            # Preserve the source aspect ratio and avoid crops or content changes.
            if image.size != size:
                raise SystemExit(f"{asset_id}: source aspect ratio does not match target {size}")
            quality = 85
            while True:
                buf = io.BytesIO()
                image.save(buf, format="JPEG", quality=quality, optimize=True, progressive=True)
                data = buf.getvalue()
                if len(data) <= LIMIT:
                    break
                quality -= 2
                if quality < 68:
                    raise SystemExit(f"{asset_id}: cannot meet 180KB limit")
            filename = f"{asset_id}-v1.jpg"
            (out / filename).write_bytes(data)
            manifest[asset_id] = {
                "id": asset_id, "filename": filename, "mime": "image/jpeg",
                "width": image.width, "height": image.height, "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(), "version": "v1",
            }
            encoded[asset_id] = base64.b64encode(data).decode("ascii")
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    lines = ["// Generated by scripts/build-tavern-art.py; do not edit by hand.", "export default {"]
    for asset_id, data in encoded.items():
        lines.append(f"  {json.dumps(asset_id)}: {{ mime: 'image/jpeg', base64: '{data}' }},")
    lines.append("};")
    (ROOT / "tavern-art-data.mjs").write_text("\n".join(lines) + "\n")
    for asset_id, item in manifest.items():
        print(f"{asset_id}: {item['width']}x{item['height']} {item['bytes']} bytes sha256={item['sha256']}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("pairs", nargs="+", help="asset-id=source-image path")
    args = parser.parse_args()
    pairs = []
    for pair in args.pairs:
        asset_id, sep, path = pair.partition("=")
        if not sep or asset_id not in TARGETS:
            parser.error(f"invalid pair: {pair}")
        pairs.append((asset_id, Path(path)))
    build(pairs)


if __name__ == "__main__":
    main()
