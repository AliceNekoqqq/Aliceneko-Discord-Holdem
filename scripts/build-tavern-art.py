#!/usr/bin/env python3
"""Build optimized tavern JPEGs and a compact static-asset manifest."""
import argparse
import hashlib
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PROMPTS = ROOT / "assets" / "art" / "prompts.json"
TARGETS = {
    asset["id"]: (960, 640) if asset["id"] == "room" else (512, 512)
    for asset in json.loads(PROMPTS.read_text())["assets"]
}
LIMIT = 180 * 1024


def build(pairs):
    supplied = dict(pairs)
    if len(supplied) != len(pairs) or set(supplied) != set(TARGETS):
        raise SystemExit("provide every prompt ID exactly once; preserve existing image paths")
    out = ROOT / "assets" / "art"
    out.mkdir(parents=True, exist_ok=True)
    manifest = {}
    previous = json.loads((out / "manifest.json").read_text()) if (out / "manifest.json").exists() else {}
    for asset_id, size in TARGETS.items():
        with Image.open(supplied[asset_id]) as source:
            image = source.convert("RGB")
            image.thumbnail(size, Image.Resampling.LANCZOS)
            if image.size != size:
                raise SystemExit(f"{asset_id}: source aspect ratio does not match target {size}")
            existing = supplied[asset_id].read_bytes()
            keep = source.format == "JPEG" and hashlib.sha256(existing).hexdigest() == previous.get(asset_id, {}).get("sha256")
            quality = 85
            while not keep:
                buf = io.BytesIO()
                image.save(buf, format="JPEG", quality=quality, optimize=True, progressive=True)
                data = buf.getvalue()
                if len(data) <= LIMIT:
                    break
                quality -= 2
                if quality < 68:
                    raise SystemExit(f"{asset_id}: cannot meet 180KB limit")
            if keep:
                data = existing
            filename = f"{asset_id}-v1.jpg"
            (out / filename).write_bytes(data)
            manifest[asset_id] = {
                "id": asset_id, "filename": filename, "mime": "image/jpeg",
                "width": image.width, "height": image.height, "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(), "version": "v1",
            }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (ROOT / "tavern-art-manifest.mjs").write_text(
        "// Generated by scripts/build-tavern-art.py; do not edit by hand.\nexport default "
        + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n"
    )
    for generated in ROOT.glob("tavern-art-data*.mjs"):
        generated.unlink()
    for asset_id, item in manifest.items():
        print(f"{asset_id}: {item['width']}x{item['height']} {item['bytes']} bytes sha256={item['sha256']}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("pairs", nargs="+", help="asset-id=source-image path")
    args = parser.parse_args()
    pairs = []
    for pair in args.pairs:
        asset_id, sep, path = pair.partition("=")
        if not sep or asset_id not in TARGETS:
            parser.error(f"invalid pair: {pair}")
        pairs.append((asset_id, Path(path)))
    build(pairs)


if __name__ == "__main__":
    main()
