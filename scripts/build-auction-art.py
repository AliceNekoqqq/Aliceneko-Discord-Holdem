#!/usr/bin/env python3
"""Build 24 inventory images and an RGBA renderer atlas from the approved source."""
import hashlib
import json
from io import BytesIO
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]

def build():
    source = ROOT / 'assets/auction-art/atlas-v1.webp'
    image = Image.open(source).convert('RGBA')
    if image.size != (1024, 1536):
        raise ValueError('Auction source must be a 4 by 6 grid of 256px cells')
    public = ROOT / 'public/art/auction'
    public.mkdir(parents=True, exist_ok=True)
    atlas = Image.new('RGBA', (512, 768))
    items = {}
    # Inspected source-specific cuts keep the slightly raised lower rows separate.
    row_cuts = [0, 253, 507, 755, 1005, 1245, 1536]
    for quality in range(6):
        for variant in range(4):
            item_id = f'tavern-{quality}-{variant}'
            art = image.crop((variant*256+8, row_cuts[quality], (variant+1)*256-8, row_cuts[quality+1]))
            art.thumbnail((232, 232), Image.Resampling.LANCZOS)
            icon = Image.new('RGBA', (256, 256))
            icon.paste(art, ((256-art.width)//2, (256-art.height)//2))
            encoded = BytesIO()
            icon.save(encoded, format='PNG', optimize=True)
            content = encoded.getvalue()
            if not content.startswith(b'\x89PNG\r\n\x1a\n'):
                raise ValueError(f'Invalid auction icon: {item_id}')
            (public / f'{item_id}-v1.png').write_bytes(content)
            small = icon.resize((128, 128), Image.Resampling.LANCZOS)
            atlas.paste(small, (variant*128, quality*128))
            items[item_id] = {'x': variant*128, 'y': quality*128, 'path': f'/art/auction/{item_id}-v1.png', 'bytes': len(content), 'sha256': hashlib.sha256(content).hexdigest()}
    pixels = atlas.tobytes()
    (public / 'sprites-v1.bin').write_bytes(pixels)
    manifest = {'width': 512, 'height': 768, 'size': 128,
                'path': '/art/auction/sprites-v1.bin', 'bytes': len(pixels),
                'sha256': hashlib.sha256(pixels).hexdigest(), 'items': items}
    (ROOT / 'auction-art-manifest.mjs').write_text('// Generated by scripts/build-auction-art.py.\nexport default '+json.dumps(manifest, ensure_ascii=False, indent=2)+';\n')
    return manifest

if __name__ == '__main__':
    result = build()
    print(json.dumps({'images': len(result['items']), 'atlasBytes': result['bytes']}))
