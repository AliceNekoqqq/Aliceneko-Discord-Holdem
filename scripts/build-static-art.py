#!/usr/bin/env python3
"""Copy all approved image sources and generated binary atlases into public/."""
import hashlib
import json
import re
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public" / "art"


def publish(source, relative_path, mime):
    target = ROOT / "public" / relative_path
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    data = source.read_bytes()
    width = height = None
    if mime in ("image/jpeg", "image/png"):
        with Image.open(source) as image:
            expected = "JPEG" if mime == "image/jpeg" else "PNG"
            if image.format != expected:
                raise ValueError(f"Invalid {mime} source: {source}")
            width, height = image.size
    record = {
        "path": "/" + relative_path.replace("\\", "/"),
        "mime": mime,
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }
    if width is not None:
        record.update(width=width, height=height)
    return record


def write_module(name, value, comment):
    (ROOT / name).write_text(
        comment + "\nexport default " + json.dumps(value, ensure_ascii=False, indent=2) + ";\n"
    )


def main():
    if PUBLIC.exists():
        shutil.rmtree(PUBLIC)
    PUBLIC.mkdir(parents=True)
    totals = {"images": 0, "bytes": 0}
    tavern = {}
    for source in sorted((ROOT / "assets" / "art").glob("*-v1.jpg")):
        match = re.fullmatch(r"([a-z0-9-]+)-v1\.jpg", source.name)
        if not match:
            continue
        asset_id = match.group(1)
        record = publish(source, f"art/{asset_id}/v1.jpg", "image/jpeg")
        record.update(id=asset_id, filename=source.name, version="v1")
        tavern[asset_id] = record
    if not tavern or "room" not in tavern:
        raise FileNotFoundError("Tavern room and menu JPEGs are required")
    write_module("tavern-art-manifest.mjs", tavern, "// Generated by scripts/build-static-art.py.")

    # Versioned UGC sources retain their dish/revision filename under ASSETS.
    ugc_dir = ROOT / "assets" / "ugc-art"
    for source in sorted(ugc_dir.glob("*.jpg")):
        if not re.fullmatch(r"ugc_[a-z0-9]+-r[1-9][0-9]*-[a-f0-9]+\.jpg", source.name):
            raise ValueError(f"Invalid versioned UGC image name: {source.name}")
        publish(source, f"art/ugc/{source.name}", "image/jpeg")

    equipment_manifest = json.loads((ROOT / "assets" / "equipment-art" / "manifest.json").read_text())
    for asset_id in equipment_manifest:
        source = ROOT / "assets" / "equipment-art" / f"{asset_id}.jpg"
        if not source.is_file():
            raise FileNotFoundError(source)
        publish(source, f"art/equipment/{asset_id}/v1.jpg", "image/jpeg")

    pets = {"v1": {}, "v2": {}}
    for version, filename in (("v1", "manifest.json"), ("v2", "manifest-v2.json")):
        rows = json.loads((ROOT / "assets" / "pets" / filename).read_text())
        for row in rows:
            species, coat = row["species"], row["coat"]
            source = ROOT / "assets" / "pets" / f"{species}-{coat}-{version}.jpg"
            record = publish(source, f"art/pets/{species}/{coat}/{version}.jpg", "image/jpeg")
            if record["bytes"] != row["bytes"] or record["sha256"] != row["sha256"]:
                raise ValueError(f"Pet manifest mismatch: {source}")
            record.update(species=species, coat=coat)
            pets[version][f"{species}:{coat}"] = record
    write_module("pet-art-manifest.mjs", pets, "// Generated by scripts/build-static-art.py.")

    walk = {"scenes": {}, "maps": {}}
    walk_dir = ROOT / "assets" / "pet-walk"
    for source in sorted(walk_dir.glob("*.jpg")):
        scene_id = source.stem
        record = publish(source, f"art/pet-walk/scenes/{scene_id}/v1.jpg", "image/jpeg")
        walk["scenes"][scene_id] = record
    for source in sorted((walk_dir / "maps").glob("*.png")):
        state = source.stem
        record = publish(source, f"art/pet-walk/maps/{state}/v1.png", "image/png")
        walk["maps"][state] = record
    if len(walk["scenes"]) != 6 or set(walk["maps"]) != {"0", "1", "2", "3", "4", "done"}:
        raise ValueError("Expected six pet-walk scenes and six map states")
    write_module("pet-walk-art-manifest.mjs", walk, "// Generated by scripts/build-static-art.py.")

    renderer = ROOT / "assets" / "renderer"
    for name in ("card-glyphs.bin", "nickname-glyphs.bin", "emoji-sprites.bin"):
        source = renderer / name
        if not source.is_file():
            raise FileNotFoundError(f"Run the renderer atlas builder first: {source}")
        publish(source, f"art/renderer/{name}", "application/octet-stream")

    all_public = list(PUBLIC.rglob("*"))
    files = [path for path in all_public if path.is_file()]
    totals["images"] = len(files)
    totals["bytes"] = sum(path.stat().st_size for path in files)
    print(json.dumps(totals))


if __name__ == "__main__":
    main()
