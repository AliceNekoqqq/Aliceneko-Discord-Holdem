const current = state => state?.ruleVersion === 'lantern-rules-v0.11' ? latest : state?.ruleVersion === 'lantern-rules-v0.10' ? v10 : state?.ruleVersion === 'lantern-rules-v0.9' ? v09 : state?.ruleVersion === 'lantern-rules-v0.8' ? v08 : state?.ruleVersion === 'lantern-rules-v0.7' ? previous : state?.ruleVersion === 'lantern-rules-v0.6' ? expanded : legacy;
export const beginBattle = options => current(options).beginBattle(options);
export const battleAction = (state, action) => current(state).battleAction(state, action);
export const legalCards = state => current(state).legalCards(state);
export const legalItems = state => current(state).legalItems?.(state) ?? [];
