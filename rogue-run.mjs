import * as legacy from './rogue-run-v04.mjs';
import * as expanded from './rogue-run-v06.mjs';
import * as previous from './rogue-run-v07.mjs';
import * as v08 from './rogue-run-v08.mjs';
import * as v09 from './rogue-run-v09.mjs';
import * as v10 from './rogue-run-v10.mjs';
import * as latest from './rogue-run-v11.mjs';
export const RULE_VERSION = legacy.RULE_VERSION;
export const V06_RULE_VERSION = 'lantern-rules-v0.6';
export const V07_RULE_VERSION = 'lantern-rules-v0.7';
export const V08_RULE_VERSION = 'lantern-rules-v0.8';
export const V09_RULE_VERSION = 'lantern-rules-v0.9';
export const V10_RULE_VERSION = 'lantern-rules-v0.10';
export const CURRENT_RULE_VERSION = 'lantern-rules-v0.11';
export const SUPPORTED_RULE_VERSIONS = [RULE_VERSION, V06_RULE_VERSION, V07_RULE_VERSION, V08_RULE_VERSION, V09_RULE_VERSION, V10_RULE_VERSION, CURRENT_RULE_VERSION];
export const RunActionError = legacy.RunActionError;
const current = run => run?.ruleVersion === CURRENT_RULE_VERSION ? latest : run?.ruleVersion === V10_RULE_VERSION ? v10 : run?.ruleVersion === V09_RULE_VERSION ? v09 : run?.ruleVersion === V08_RULE_VERSION ? v08 : run?.ruleVersion === V07_RULE_VERSION ? previous : run?.ruleVersion === V06_RULE_VERSION ? expanded : legacy;
export const createRun = options => current(options).createRun(options);
export const runAction = (run, action, now) => current(run).runAction(run, action, now);
export const expireRun = (run, now) => current(run).expireRun(run, now);
